export function renderExhibit([type,...values]) {
  if (type === 'table') return recordTable('기록 원문',values[0],values[1],'');
  if (type === 'route') return '<ol class="exhibit evidence-route">'+values[0].map(point=>'<li>'+point+'</li>').join('')+'</ol>';
  if (type === 'photos') {
    const [id,left,right,description] = values;
    return '<figure class="exhibit comparison"><a class="evidence-photo-link" href="/evidence-'+id+'.webp" target="_blank" rel="noopener" aria-label="증거 사진 확대 (새 탭)"><div class="evidence-composite"><img src="/evidence-'+id+'.webp" alt="'+description+'"><div><time>'+left+'</time><time>'+right+'</time></div></div><figcaption>사진 확대 ↗</figcaption></a></figure>';
  }
  if (type === 'box') {
    return '<figure class="exhibit ballot-diagram"><div class="ballot-sections"><div><b>받침 분리</b><span class="ballot-slot">▰ &nbsp; 옆 칸 · 닫힘</span><span class="ballot-main">본체 바닥</span></div><div><b>받침 결합</b><span class="ballot-slot">옆 칸 · 열림 &nbsp; ↘</span><span class="ballot-main">본체 바닥 &nbsp; ▰</span></div></div><figcaption>개표함 단면 · 결합 전후 비교</figcaption></figure>';
  }
  const heights = [10,17,12,35,12,9,40,13,6,9,20,26,16,29,37,16,27,34,15,25,19,13,8,17,12,10];
  const waveform = heights.map((height,index)=>'<i class="'+([3,6].includes(index)?'tap':'')+'" style="--bar:'+height+'px"></i>').join('');
  return '<figure class="exhibit audio-compare">'+['21:42 · 리허설 원본','22:00:08 · 청취자 수신본'].map(label=>
    '<div><b>'+label+'</b><div class="waveform" aria-hidden="true">'+waveform+'</div></div>').join('')+
    '<figcaption>노란 봉우리 두 개는 책상을 두드린 소리</figcaption></figure>';
}
